def reset_attempt_tracking_for_generation(
    state: dict,
    generation_id: int,
    fingerprint_limit: int = 1200,
    key_limit: int = 2400,
) -> bool:
    current_generation = int(state.get("attempt_generation_id") or 0)
    if current_generation != generation_id:
        state["attempt_generation_id"] = generation_id
        state["attempted_fingerprints"] = []
        state["attempted_keys"] = []
        state["template_error_counts"] = {}
        append_history(
            state,
            {
                "ts": utc_now(),
                "event": "attempt_tracking_reset",
                "generation_id": generation_id,
                "previous_generation_id": current_generation,
            },
        )
        return True

    state["attempted_fingerprints"] = list(state.get("attempted_fingerprints") or [])[-fingerprint_limit:]
    state["attempted_keys"] = list(state.get("attempted_keys") or [])[-key_limit:]
    return False


def recover_stale_submission_flow(
    state: dict,
    supply_summary: dict,
    stale_minutes: int,
    active_running: int,
) -> bool:
    if stale_minutes <= 0 or active_running > 0:
        return False
    last_submit_at = iso_to_timestamp(state.get("last_submit_at"))
    if last_submit_at is None:
        return False
    stale_seconds = max(60, stale_minutes * 60)
    if datetime.now(timezone.utc).timestamp() - last_submit_at < stale_seconds:
        return False
    generation_id = int(supply_summary.get("generation_id") or 0)
    state["attempted_fingerprints"] = []
    state["attempted_keys"] = []
    state["template_error_counts"] = {}
    state["attempt_generation_id"] = generation_id
    append_history(
        state,
        {
            "ts": utc_now(),
            "event": "stale_submit_recovery",
            "generation_id": generation_id,
            "last_submit_at": state.get("last_submit_at"),
            "stale_minutes": stale_minutes,
        },
    )
    return True


def _safe_float(value, default: float = 0.0) -> float:
    try:
        if value is None:
            return default
        return float(value)
    except Exception:
        return default


def iso_to_timestamp(value: str | None) -> float | None:
    if not value:
        return None
    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00")).timestamp()
    except Exception:
        return None


def reward_from_result(result: dict) -> float:
    details = result.get("alpha_details") or {}
    is_block = details.get("is") or {}
    sharpe = _safe_float(is_block.get("sharpe"))
    fitness = _safe_float(is_block.get("fitness"))
    returns = _safe_float(is_block.get("returns"))
    margin = _safe_float(is_block.get("margin"))
    turnover = abs(_safe_float(is_block.get("turnover")))
    reward = sharpe * 0.45 + fitness * 0.35 + returns * 3.0 + margin * 150.0
    if sharpe > 2.0 and fitness > 2.0:
        reward += 0.4
    if turnover > 0.7:
        reward -= 0.3
    return reward


