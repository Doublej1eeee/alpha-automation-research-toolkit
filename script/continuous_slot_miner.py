def disable_operator_from_error(message: str, source: str = "") -> bool:
    match = re.search(r'unknown operator "([^"]+)"', str(message or ""), flags=re.IGNORECASE)
    if not match:
        match = re.search(r'inaccessible or unknown operator "([^"]+)"', str(message or ""), flags=re.IGNORECASE)
    if not match:
        return False
    operator = match.group(1).strip()
    wrappers = OPERATOR_WRAPPER_MAP.get(operator, [])
    if not wrappers:
        return False
    payload = load_runtime_guardrails()
    disabled_wrappers = list(payload.get("disabled_wrappers") or [])
    disabled_operators = list(payload.get("disabled_operators") or [])
    changed = False
    for wrapper in wrappers:
        if wrapper not in disabled_wrappers:
            disabled_wrappers.append(wrapper)
            changed = True
    if operator not in disabled_operators:
        disabled_operators.append(operator)
        changed = True
    if not changed:
        return False
    events = list(payload.get("events") or [])
    events.append(
        {
            "ts": utc_now(),
            "event": "operator_disabled",
            "operator": operator,
            "wrappers": wrappers,
            "source": source,
        }
    )
    payload["disabled_wrappers"] = disabled_wrappers[-100:]
    payload["disabled_operators"] = disabled_operators[-100:]
    payload["events"] = events[-300:]
    save_runtime_guardrails(payload)
    print(f"[RUNTIME GUARDRAIL] disabled operator={operator} wrappers={wrappers} source={source}")
    return True


def inventory_guardrail_key(job: dict) -> str:
    return str(job.get("inventory_name") or job.get("name") or Path(str(job.get("template"))).stem)


def inventory_is_paused(job: dict) -> tuple[bool, dict]:
    key = inventory_guardrail_key(job)
    payload = load_runtime_guardrails()
    inventories = payload.get("paused_inventories") or {}
    row = inventories.get(key) if isinstance(inventories, dict) else None
    if not isinstance(row, dict):
        return False, {}
    until_raw = row.get("paused_until")
    try:
        until_ts = datetime.fromisoformat(str(until_raw).replace("Z", "+00:00")).timestamp()
    except Exception:
        return False, row
    return datetime.now(timezone.utc).timestamp() < until_ts, row


def pause_inventory(job: dict, reason: str, minutes: int = 240) -> None:
    key = inventory_guardrail_key(job)
    payload = load_runtime_guardrails()
    inventories = payload.get("paused_inventories") or {}
    if not isinstance(inventories, dict):
        inventories = {}
    until_ts = datetime.now(timezone.utc).timestamp() + max(5, minutes) * 60
    paused_until = datetime.fromtimestamp(until_ts, timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")
    row = dict(inventories.get(key) or {})
    row["reason"] = reason
    row["paused_until"] = paused_until
    row["count"] = int(row.get("count") or 0) + 1
    row["last_seen_at"] = utc_now()
    inventories[key] = row
    events = list(payload.get("events") or [])
    events.append({"ts": utc_now(), "event": "inventory_paused", "inventory": key, "reason": reason, "paused_until": paused_until})
    payload["paused_inventories"] = inventories
    payload["events"] = events[-300:]
    save_runtime_guardrails(payload)
    print(f"[INVENTORY PAUSE] {key} | reason={reason} | until={paused_until}")


def append_history(state: dict, event: dict, limit: int = 300) -> None:
    history = state.setdefault("history", [])
    history.append(event)
    if len(history) > limit:
        del history[:-limit]


def append_recent_unique(values: list[str], value: str, limit: int) -> list[str]:
    if not value:
        return values
    updated = [item for item in values if item != value]
    updated.append(value)
    if len(updated) > limit:
        del updated[:-limit]
    return updated


def read_recent_rate_limit_events(window_minutes: int) -> list[dict]:
    if not RATE_LIMIT_EVENTS_FILE.exists():
        return []
    try:
        lines = RATE_LIMIT_EVENTS_FILE.read_text(encoding="utf-8").splitlines()
    except Exception:
        return []

    now = datetime.now(timezone.utc)
    events: list[dict] = []
    for line in reversed(lines):
        line = line.strip()
        if not line:
            continue
        try:
            payload = json.loads(line)
        except Exception:
            continue
        raw_ts = payload.get("ts")
        if not raw_ts:
            continue
        try:
            event_ts = datetime.fromisoformat(str(raw_ts).replace("Z", "+00:00"))
        except Exception:
            continue
        age_minutes = (now - event_ts).total_seconds() / 60
        if age_minutes > window_minutes:
            break
        events.append(payload)
    return events


def choose_adaptive_limits(config: dict, default_active_job_slots: int) -> dict:
    adaptive_cfg = config.get("adaptive_rate_limit") or {}
    if not adaptive_cfg.get("enabled", True):
        return {
            "mode": "disabled",
            "event_count": 0,
            "active_job_slots": max(1, default_active_job_slots),
            "worker_cap": None,
            "cycle_sleep_seconds": None,
        }

    window_minutes = int(adaptive_cfg.get("window_minutes", 15))
    medium_count = int(adaptive_cfg.get("medium_429_count", 8))
    high_count = int(adaptive_cfg.get("high_429_count", 20))
    events = read_recent_rate_limit_events(window_minutes)
    event_count = len(events)

    medium_slots = int(adaptive_cfg.get("medium_active_job_slots", min(default_active_job_slots, 2)))
    high_slots = int(adaptive_cfg.get("high_active_job_slots", 1))
    low_worker_cap = adaptive_cfg.get("low_worker_cap")
    medium_worker_cap = adaptive_cfg.get("medium_worker_cap", 1)
    high_worker_cap = adaptive_cfg.get("high_worker_cap", 1)
    medium_cycle_sleep = adaptive_cfg.get("medium_cycle_sleep_seconds")
    high_cycle_sleep = adaptive_cfg.get("high_cycle_sleep_seconds")

    if event_count >= high_count:
        return {
            "mode": "high",
            "event_count": event_count,
            "active_job_slots": max(1, high_slots),
            "worker_cap": int(high_worker_cap) if high_worker_cap is not None else 1,
            "cycle_sleep_seconds": int(high_cycle_sleep) if high_cycle_sleep is not None else None,
        }
    if event_count >= medium_count:
        return {
            "mode": "medium",
            "event_count": event_count,
            "active_job_slots": max(1, medium_slots),
            "worker_cap": int(medium_worker_cap) if medium_worker_cap is not None else 1,
            "cycle_sleep_seconds": int(medium_cycle_sleep) if medium_cycle_sleep is not None else None,
        }
    return {
        "mode": "low",
        "event_count": event_count,
        "active_job_slots": max(1, default_active_job_slots),
        "worker_cap": int(low_worker_cap) if low_worker_cap is not None else None,
        "cycle_sleep_seconds": None,
    }


def classify_error_kind(message: str | None) -> str:
    text = str(message or "").lower()
    if not text:
        return "unknown"
    if "incorrect authentication credentials" in text or "submit status: 401" in text or "login failed" in text:
        return "auth_expired"
    if "does not support event inputs" in text:
        return "event_input_incompatible"
    if "incompatible unit" in text:
        return "unit_incompatible"
    if "invalid number of inputs" in text:
        return "invalid_input_arity"
    if "does not support group inputs" in text:
        return "group_input_incompatible"
    if "does not support vector inputs" in text:
        return "vector_input_incompatible"
    if "429" in text or "rate-limited" in text or "concurrent limit reached" in text:
        return "rate_limited"
    if "simulation polling timed out" in text or "simulation polling stalled" in text:
        return "simulation_poll_timeout"
    if "unknown variable" in text:
        return "unknown_variable"
    if "simulation finished without alpha id" in text:
        return "simulation_error_without_alpha_id"
    return "unknown"


