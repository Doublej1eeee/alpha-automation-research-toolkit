def field_is_compatible_with_job(field: dict, job: dict) -> tuple[bool, list[str]]:
    context = load_job_template_context(job)
    if context is None:
        return True, []
    decision = score_field_record(field, context)
    return decision.score >= 0, list(decision.reasons)


def inventory_compatibility_report(job: dict) -> dict:
    path = inventory_json_for(job)
    report = {
        "checked": False,
        "incompatible_count": 0,
        "field_type_counts": {},
        "sample_incompatible": [],
        "missing_compatibility_metadata": False,
    }
    if not path.exists():
        return report
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return report
    fields = payload.get("fields") if isinstance(payload, dict) else []
    if not isinstance(fields, list):
        return report
    context = load_job_template_context(job)
    if context is None:
        return report
    report["checked"] = True
    if "compatible_record_count" not in payload and not payload.get("compatibility_checked_at"):
        report["missing_compatibility_metadata"] = True
    type_counts: dict[str, int] = {}
    sample: list[dict] = []
    incompatible_count = 0
    for field in fields:
        if not isinstance(field, dict):
            continue
        field_type = str(field.get("type") or "UNKNOWN").upper()
        type_counts[field_type] = type_counts.get(field_type, 0) + 1
        decision = score_field_record(field, context)
        if decision.score >= 0:
            continue
        incompatible_count += 1
        if len(sample) < 8:
            sample.append(
                {
                    "id": field.get("id"),
                    "type": field_type,
                    "reasons": decision.reasons,
                }
            )
    report["field_type_counts"] = type_counts
    report["incompatible_count"] = incompatible_count
    report["sample_incompatible"] = sample
    return report


def stamp_inventory_compatibility(job: dict) -> None:
    path = inventory_json_for(job)
    if not path.exists():
        return
    report = inventory_compatibility_report(job)
    if not report.get("checked") or int(report.get("incompatible_count") or 0) > 0:
        return
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return
    payload["compatibility_checked_at"] = utc_now()
    payload["compatibility_field_type_counts"] = report.get("field_type_counts") or {}
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def sanitize_inventory_to_compatible_fields(job: dict) -> int:
    path = inventory_json_for(job)
    if not path.exists():
        return len(load_inventory_fields(job))
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return len(load_inventory_fields(job))
    fields = payload.get("fields") if isinstance(payload, dict) else []
    if not isinstance(fields, list):
        return len(load_inventory_fields(job))
    compatible_fields: list[dict] = []
    removed_fields: list[dict] = []
    for field in fields:
        if not isinstance(field, dict):
            continue
        compatible, reasons = field_is_compatible_with_job(field, job)
        if compatible:
            compatible_fields.append(field)
        elif len(removed_fields) < 20:
            removed_fields.append(
                {
                    "id": field.get("id"),
                    "type": field.get("type"),
                    "reasons": reasons,
                }
            )
    payload["fields"] = compatible_fields
    payload["selected_record_count"] = len(compatible_fields)
    payload["compatible_record_count"] = len(compatible_fields)
    payload["compatibility_checked_at"] = utc_now()
    payload["compatibility_sanitized_at"] = utc_now()
    payload["compatibility_removed_count"] = max(0, len(fields) - len(compatible_fields))
    payload["compatibility_removed_sample"] = removed_fields
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    txt_path = inventory_file_for(job)
    txt_path.write_text(
        "\n".join(str(field.get("id") or "") for field in compatible_fields if field.get("id")) + "\n",
        encoding="utf-8",
    )
    if removed_fields:
        print(
            f"[INVENTORY SANITIZE] {path.stem} | kept={len(compatible_fields)} | "
            f"removed={len(fields) - len(compatible_fields)} | sample={removed_fields[:5]}"
        )
    return len(compatible_fields)


