#!/usr/bin/env python
"""Slot-level continuous miner for large-scale BRAIN simulations.

This is the sturdier project-native absorption of worldquant-miner's best idea:
keep a fixed number of simulation slots busy, and refill a slot immediately
after it completes. It deliberately reuses this project's safer assets:
- supply jobs/templates generated by continuous_supply_engine.py
- shared field inventories
- fingerprint de-duplication
- local result storage and platform color sync from brain_client.py
- structured 429 telemetry and adaptive concurrency

It does not final-submit alphas.
"""

