def load_inventory_fields(job: dict) -> list[str]:
    path = inventory_file_for(job)
    if not path.exists():
        return []
    field_ids = [
        line.strip()
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.strip().startswith("#")
    ]
    json_path = inventory_json_for(job)
    if not json_path.exists():
        return field_ids
    try:
        payload = json.loads(json_path.read_text(encoding="utf-8"))
    except Exception:
        return field_ids
    fields = payload.get("fields") if isinstance(payload, dict) else []
    if not isinstance(fields, list):
        return field_ids
    compatible_ids: set[str] = set()
    for field in fields:
        if not isinstance(field, dict):
            continue
        field_id = str(field.get("id") or "").strip()
        if not field_id:
            continue
        compatible, _ = field_is_compatible_with_job(field, job)
        if compatible:
            compatible_ids.add(field_id)
    if not compatible_ids:
        return []
    return [field_id for field_id in field_ids if field_id in compatible_ids]


