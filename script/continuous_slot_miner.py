def ensure_inventory(job: dict, min_pool_size: int) -> bool:
    specs = slot_inventory_specs(job)
    if specs:
        ok = True
        for slot, spec in specs.items():
            refresh_inventory, inventory_state = should_refresh_inventory(spec, min_pool_size=min_pool_size)
            print(
                f"[INVENTORY CHECK] {inventory_state['inventory_name']} | slot={slot} | refresh={refresh_inventory} | "
                f"selected={inventory_state['selected_count']} | completed={inventory_state['completed_count']} | "
                f"pool_size={inventory_state['pool_size']} | age_minutes={inventory_state['age_minutes']} | "
                f"paused={bool(inventory_state.get('paused'))}"
            )
            if inventory_state.get("paused"):
                ok = False
                continue
            if not refresh_inventory and inventory_state["selected_count"] >= min_pool_size:
                continue
            ok = ok and build_inventory_with_fallback(spec, inventory_state, min_pool_size=min_pool_size)
        return ok

    fixed_slots = fixed_expression_slots(job)
    if fixed_slots == []:
        return True

    refresh_inventory, inventory_state = should_refresh_inventory(job, min_pool_size=min_pool_size)
    print(
        f"[INVENTORY CHECK] {inventory_state['inventory_name']} | refresh={refresh_inventory} | "
        f"selected={inventory_state['selected_count']} | completed={inventory_state['completed_count']} | "
        f"pool_size={inventory_state['pool_size']} | age_minutes={inventory_state['age_minutes']} | "
        f"paused={bool(inventory_state.get('paused'))}"
    )
    if inventory_state.get("paused"):
        return False
    if not refresh_inventory and inventory_state["selected_count"] >= min_pool_size:
        return True
    return build_inventory_with_fallback(job, inventory_state, min_pool_size=min_pool_size)


def resolve_template(path_text: str) -> Path:
    path = Path(path_text)
    if not path.exists():
        path = ROOT_DIR / path_text
    return path.resolve()


def fixed_expression_slots(job: dict) -> list[str] | None:
    if is_high_grade_repair_job(job):
        template_path = resolve_template(str(job["template"]))
        template = load_template(template_path)
        slots = extract_field_slots(template)
        if not slots:
            return []
        return slots
    if not bool(job.get("fixed_expression_template")):
        return None
    template_path = resolve_template(str(job["template"]))
    template = load_template(template_path)
    return extract_field_slots(template)


@dataclass
class Candidate:
    job_name: str
    supply_mode: str
    mechanism_id: str
    raw_alpha_family: str
    template_path: Path
    fields: dict[str, str]
