def update_optimizer_from_reward(state: dict, reward: float, success: bool, miner_cfg: dict) -> None:
    optimizer = ensure_optimizer_state(state, miner_cfg)
    rewards = optimizer.setdefault("recent_rewards", [])
    statuses = optimizer.setdefault("recent_status", [])
    rewards.append(reward)
    statuses.append(1 if success else 0)
    if len(rewards) > 120:
        del rewards[:-120]
    if len(statuses) > 120:
        del statuses[:-120]

    completed = int(state.get("completed") or 0) + int(state.get("errors") or 0)
    interval = int(optimizer.get("optimization_interval") or 18)
    last_optimized = int(optimizer.get("last_optimized_completed") or 0)
    if completed - last_optimized < interval:
        return

    recent_rewards = rewards[-interval:]
    recent_statuses = statuses[-interval:]
    avg_reward = sum(recent_rewards) / max(len(recent_rewards), 1)
    success_rate = sum(recent_statuses) / max(len(recent_statuses), 1)
    exploration_rate = float(optimizer.get("exploration_rate") or 0.28)
    min_rate = float(optimizer.get("min_exploration_rate") or 0.08)
    max_rate = float(optimizer.get("max_exploration_rate") or 0.55)

    if success_rate < 0.22 or avg_reward < 0.8:
        exploration_rate = min(max_rate, exploration_rate * 1.12)
    elif success_rate > 0.4 and avg_reward > 1.4:
        exploration_rate = max(min_rate, exploration_rate * 0.92)
    elif avg_reward > 1.0:
        exploration_rate = max(min_rate, exploration_rate * 0.97)

    optimizer["exploration_rate"] = round(exploration_rate, 4)
    optimizer["last_optimized_completed"] = completed
    optimizer["last_avg_reward"] = round(avg_reward, 6)
    optimizer["last_success_rate"] = round(success_rate, 6)


def update_job_bandit(state: dict, job_name: str, reward: float, success: bool) -> None:
    bandit = state.setdefault("job_bandit", {})
    arm = bandit.setdefault(
        job_name,
        {
            "alpha": 1.0,
            "beta": 1.0,
            "pulls": 0,
            "reward_sum": 0.0,
            "avg_reward": 0.0,
            "successes": 0,
        },
    )
    arm["pulls"] = int(arm.get("pulls") or 0) + 1
    arm["reward_sum"] = _safe_float(arm.get("reward_sum")) + reward
    arm["avg_reward"] = arm["reward_sum"] / max(arm["pulls"], 1)
    if success:
        arm["successes"] = int(arm.get("successes") or 0) + 1
    normalized_reward = max(0.0, min(1.0, (reward + 1.0) / 2.0))
    arm["alpha"] = _safe_float(arm.get("alpha"), 1.0) + normalized_reward
    arm["beta"] = _safe_float(arm.get("beta"), 1.0) + (1.0 - normalized_reward)


def job_sampling_score(job: dict, state: dict, exploration_rate: float) -> float:
    base_priority = _safe_float(job.get("supply_priority"))
    job_name = str(job.get("name") or "")
    bandit = state.get("job_bandit") or {}
    arm = bandit.get(job_name) or {}
    alpha = max(_safe_float(arm.get("alpha"), 1.0), 0.01)
    beta = max(_safe_float(arm.get("beta"), 1.0), 0.01)
    sampled = random.betavariate(alpha, beta)
    avg_reward = _safe_float(arm.get("avg_reward"))
    pulls = int(arm.get("pulls") or 0)
    confidence_bonus = min(0.35, math.log1p(max(pulls, 0)) / 15.0)
    random_jitter = random.random() * max(0.05, exploration_rate * 0.6)
    raw_alpha_bonus = 0.0
    if job.get("raw_alpha_family"):
        raw_alpha_bonus = 0.75
        if pulls == 0:
            raw_alpha_bonus += 0.35
    return base_priority + raw_alpha_bonus + sampled * 0.9 + avg_reward * 0.08 + confidence_bonus + random_jitter


def choose_desired_mode(base_mode: str, supply_summary: dict, state: dict, miner_cfg: dict) -> str:
    optimizer = ensure_optimizer_state(state, miner_cfg)
    exploration_rate = float(optimizer.get("exploration_rate") or 0.28)
    search_strategy = supply_summary.get("search_strategy") or {}
    exploit_share = _safe_float(search_strategy.get("exploit_share"), 0.5)
    if random.random() < exploration_rate:
        return "explore"
    if base_mode == "exploit" and random.random() < max(0.35, exploit_share):
        return "exploit"
    if base_mode == "explore" and random.random() < max(0.35, 1.0 - exploit_share):
        return "explore"
    return base_mode


