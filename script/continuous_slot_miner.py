def build_candidate(job: dict, field_map: dict[str, str]) -> Candidate | None:
    template_path = resolve_template(str(job["template"]))
    template = load_template(template_path)
    validation = validate_template_payload(template_path, template)
    if not validation.valid:
        print(f"TEMPLATE INVALID | {template_path} | {'; '.join(validation.errors)}")
        return None
    config = replace_field_map(template, field_map)
    fingerprint = build_alpha_fingerprint(config)
    return Candidate(
        job_name=str(job.get("name") or template_path.stem),
        supply_mode=str(job.get("supply_mode") or "explore"),
        mechanism_id=str(job.get("mechanism_id") or job.get("research_mechanism_id") or ""),
        raw_alpha_family=str(job.get("raw_alpha_family") or ""),
        template_path=template_path,
        fields=dict(field_map),
        config=config,
        fingerprint=fingerprint,
    )


def slot_fields_for_job(job: dict) -> list[str]:
    slot_specs = slot_inventory_specs(job)
    if slot_specs:
        return sorted(str(slot) for slot in slot_specs.keys())
    template_path = resolve_template(str(job["template"]))
    template = load_template(template_path)
    slots = extract_field_slots(template)
    if (bool(job.get("fixed_expression_template")) or is_high_grade_repair_job(job)) and not slots:
        return []
    return slots or ["FIELD"]


def iter_field_maps(job: dict, max_pairs: int = 600, blocked_fields: set[str] | None = None) -> list[dict[str, str]]:
    blocked_fields = blocked_fields or set()
    slots = slot_fields_for_job(job)
    if not slots:
        return [{}]
    slot_specs = slot_inventory_specs(job)
    if slot_specs:
        slot_fields: dict[str, list[str]] = {}
        for slot in slots:
            fields = [field for field in load_slot_inventory_fields(job, slot) if field not in blocked_fields]
            random.shuffle(fields)
            if not fields:
                return []
            slot_fields[slot] = fields[: min(len(fields), 50)]

        if len(slots) == 1:
            return [{slots[0]: field} for field in slot_fields[slots[0]]]

        combinations: list[dict[str, str]] = []
        seen: set[tuple[str, ...]] = set()
        job_max_pairs = int(job.get("max_pair_field_maps") or max_pairs)
        max_attempts = max(job_max_pairs * 20, 400)
        attempts = 0
        while len(combinations) < job_max_pairs and attempts < max_attempts:
            attempts += 1
            mapping = {slot: random.choice(slot_fields[slot]) for slot in slots}
            values = [mapping[slot] for slot in slots]
            if len(set(values)) != len(values):
                continue
            key = tuple(values)
            if key in seen:
                continue
            seen.add(key)
            combinations.append(mapping)
        return combinations

    fields = [field for field in load_inventory_fields(job) if field not in blocked_fields]
    random.shuffle(fields)
    if not fields:
        return []
    if len(slots) == 1:
        return [{slots[0]: field} for field in fields]

    trimmed = fields[: min(len(fields), 40)]
    combinations: list[dict[str, str]] = []
    seen: set[tuple[str, ...]] = set()
    job_max_pairs = int(job.get("max_pair_field_maps") or max_pairs)
    if len(slots) == 2:
        for left in trimmed:
            for right in trimmed:
                if left == right:
                    continue
                key = (left, right)
                if key in seen:
                    continue
                seen.add(key)
                combinations.append({slots[0]: left, slots[1]: right})
                if len(combinations) >= job_max_pairs:
                    return combinations
        return combinations

    for field in trimmed:
        mapping = {slot: field for slot in slots}
        combinations.append(mapping)
        if len(combinations) >= job_max_pairs:
            break
    return combinations


def active_mechanism_order(jobs: list[dict], miner_cfg: dict) -> list[str]:
    configured = [
        str(item).strip()
        for item in (miner_cfg.get("mechanism_rotation_order") or [])
        if str(item).strip()
    ]
    present = {
        str(job.get("mechanism_id") or job.get("research_mechanism_id") or "").strip()
        for job in jobs
        if str(job.get("mechanism_id") or job.get("research_mechanism_id") or "").strip()
    }
    ordered = [item for item in configured if item in present]
    ordered.extend(sorted(present - set(ordered)))
    return ordered


def next_target_mechanism(jobs: list[dict], state: dict, miner_cfg: dict) -> str:
    if not bool(miner_cfg.get("mechanism_rotation_enabled", True)):
        return ""
    mechanisms = active_mechanism_order(jobs, miner_cfg)
    if not mechanisms:
        return ""
    cursor = int(state.get("mechanism_cursor") or 0) % len(mechanisms)
    state["mechanism_cursor"] = (cursor + 1) % len(mechanisms)
    return mechanisms[cursor]


